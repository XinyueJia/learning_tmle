from pathlib import Path
from playwright.sync_api import sync_playwright
p=Path('/mnt/data/EIF_Interactive_Tutorial.html').resolve().as_uri()
with sync_playwright() as pl:
    browser=pl.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1360,'height':900},device_scale_factor=1)
    errs=[]
    page.on('pageerror',lambda e: errs.append(str(e)))
    page.route('https://cdn.jsdelivr.net/**',lambda route: route.abort())
    page.set_content(Path('/mnt/data/EIF_Interactive_Tutorial.html').read_text(),wait_until='domcontentloaded',timeout=25000)
    page.wait_for_timeout(1200)
    print('title=',page.title())
    print('passed=',page.evaluate('window.__EIF_TESTS_PASSED__'))
    print('chapter count=',page.locator('section.chapter').count())
    print('lab count=',page.locator('.lab h3').count())
    print('errors=',errs)
    print('actual initial ATE:',page.locator('#mixMetrics .metric .v').first.inner_text())
    page.locator('#chapter-4').scroll_into_view_if_needed()
    page.screenshot(path='/mnt/data/eif_tutorial_preview.png',full_page=False)
    page.locator('#cellX').select_option('1')
    page.locator('#cellA').select_option('0')
    page.locator('#cellY').select_option('1')
    page.locator('#cellT').fill('1')
    print('cell EIF=',page.locator('#cellMetrics .metric .v').nth(2).inner_text())
    page.locator('#presetQ').click()
    print('only q estimates=',page.locator('#tmleMetrics .metric .v').all_inner_texts())
    page.locator('#presetG').click()
    print('only g estimates=',page.locator('#tmleMetrics .metric .v').all_inner_texts())
    browser.close()
