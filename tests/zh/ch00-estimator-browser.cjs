const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const base=(process.env.EIF_URL||'http://127.0.0.1:4174').replace(/(?:\/zh)?\/?$/,'/zh');
const dir=process.env.EIF_SCREENSHOT_DIR||'output/zh/playwright';
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try {fs.mkdirSync(dir,{recursive:true});for(const width of [1360,375]){
  const page=await browser.newPage({viewport:{width,height:900}}),errors=[],external=[];
  page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await page.route('**/*',r=>{const u=r.request().url();if(u.startsWith(new URL(base).origin+'/')||u.startsWith('data:'))return r.continue();external.push(u);return r.abort();});
  await page.goto(base+'/chapter-0-details.html?edition=estimator-map#chapter-0');
  const ch=page.locator('#chapter-0'),fig=ch.locator('#intro-visual-estimator-map');await fig.waitFor({state:'visible'});
  assert.deepEqual(await fig.locator('[data-estimator-component]').evaluateAll(es=>es.map(e=>e.dataset.estimatorComponent)),['sample','fit','target','estimate']);
  assert.equal(await fig.locator('.estimator-rule [data-if-position]').count(),0,'IF analysis is separate from executable plug-in workflow');
  assert.equal(await fig.locator('[data-if-position=analysis]').count(),1);
  assert.equal(await fig.locator('svg[role=img]').count(),3,'records, fitted risks and schematic influences use actual graphics');
  assert.equal(await fig.locator('[data-estimator-component=fit] [data-method-anchor=tmle]').count(),1,'TMLE marks the outcome fitting component');
  assert.equal(await fig.locator('[data-estimator-component=estimate] [data-method-anchor=aipw]').count(),1,'AIPW marks the output component');
  assert.equal(await fig.locator('[data-method-route=aipw][data-correction-position=estimate]').count(),1);
  assert.equal(await fig.locator('[data-method-route=tmle][data-correction-position=outcome-regression]').count(),1);
  assert.equal(await fig.locator('[data-method-shared-inputs=true]').count(),1);
  const shared=await fig.locator('.method-shared-inputs').innerText();
  for(const phrase of ['用药概率','互补概率','同一样本','组别比例'])assert(shared.includes(phrase),'corrections share treatment probabilities and empirical target weights');
  assert((await fig.locator('[data-guidance=eif]').innerText()).includes('只是EIF的一部分'));
  assert((await fig.locator('[data-method-route=aipw]').innerText()).includes('初始风险预测保留'));
  const tmleText=await fig.locator('[data-method-route=tmle]').innerText();
  for(const phrase of ['更新','加权残差样本平均接近0','重新标准化、相减'])assert(tmleText.includes(phrase));
  assert((await fig.locator('.method-conditions').innerText()).includes('未计算两种修正后的数值'));
  assert((await ch.textContent()).includes('有效影响函数（efficient influence function，EIF）'));
  assert((await ch.textContent()).includes('AIPW的修正发生在输出端'));
  const equationTex=await ch.locator('.equation annotation').allTextContents();
  assert(!equationTex.some(t=>t.includes('epsilon')||t.includes('frac{A')||t.includes('logit')),'macro overview does not prematurely introduce full targeting equations');

  assert.equal(await fig.locator('[data-estimate]').getAttribute('data-estimate'),'0.21');
  assert.equal(await fig.locator('[data-error]').getAttribute('data-error'),'0.01');
  assert((await fig.locator('.estimator-error-relation').innerText()).includes('剩余项足够小'));
  assert((await fig.locator('.estimator-if-average').innerText()).includes('仅为示意'));
  assert((await ch.textContent()).includes('不是从固定200条CSV实际训练得到的结果'));
  assert.equal(await fig.locator('.formula-recall').count(),1);assert(await fig.locator('math').count()>0);
  const nodes=await fig.locator('[data-estimator-component]').evaluateAll(es=>es.map(e=>{const r=e.getBoundingClientRect();return {x:r.x,y:r.y,w:r.width};}));
  if(width===1360)assert(nodes.every(n=>Math.abs(n.y-nodes[0].y)<1),'desktop shows the whole ordered workflow on one row');
  else assert(nodes.every((n,i)=>!i||n.y>nodes[i-1].y),'mobile workflow retains ordered vertical flow');
  const errorFigure=ch.locator('#intro-visual-fit-error'),details=errorFigure.locator('xpath=ancestor::details');
  assert(!(await details.evaluate(e=>e.open)));await details.locator('summary').focus();await details.locator('summary').press('Enter');
  assert(await errorFigure.isVisible());assert.deepEqual(await errorFigure.locator('.intro-error-result').allTextContents(),['拟合ATE：21 pp','拟合ATE：19 pp']);
  assert.equal(await ch.locator('.equation').count(),4);assert.equal(await ch.locator('.katex-error').count(),0);
  await details.locator('summary').press('Enter');assert(!(await details.evaluate(e=>e.open)));
  await fig.locator('.recall-trigger').click();assert(await fig.locator('.recall-popover').isVisible());
  assert((await fig.locator('.recall-popover').innerText()).includes('真实分布'));await page.keyboard.press('Escape');
  assert(await fig.evaluate(e=>e.scrollWidth<=e.clientWidth+1));
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await fig.screenshot({path:path.join(dir,`ch00-estimator-map-${width}.png`)});
  await fig.locator('.estimator-methods').screenshot({path:path.join(dir,`ch00-method-routes-${width}.png`)});
  await fig.locator('.estimator-rule').screenshot({path:path.join(dir,`ch00-method-positions-${width}.png`)});
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);await page.close();
  console.log(`PASS estimator overview ${width}px: component flow/IF position and AIPW/TMLE targets, shared EIF guidance, hypothetical values/conditions, graphics, folded example/keyboard, MathML/popover/layout/console`);
 }}finally{await browser.close();}
})().then(()=>process.exit(0)).catch(e=>{console.error(e);process.exit(1);});
